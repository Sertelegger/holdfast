// The wire tokens that live in `protocol/` as constants
// ---------------------------------------------------------------------

/// Every `pub const NAME: &str = "…"` under `src/protocol/`.
///
/// These are the wire's *vocabulary* — the method names of §7.4.1, the
/// `tool/` prefix, §18.3a's two reject tokens — and a new method is the
/// textbook additive change [`PROTOCOL_MINOR`]'s own doc names. There is
/// no runtime enumeration of them (they are free-standing consts, not an
/// array), so this one dimension is read from the source. That is the
/// weaker instrument and it is used only where nothing stronger exists;
/// it matches a **declaration**, so prose that mentions a method name
/// does not enter the document and a comment cannot move it.
fn wire_tokens() -> Vec<String> {
    let dir = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("src/protocol");
    let mut files: Vec<PathBuf> = std::fs::read_dir(&dir)
        .unwrap_or_else(|e| panic!("read {}: {e}", dir.display()))
        .map(|e| e.expect("dir entry").path())
        .filter(|p| p.extension().is_some_and(|x| x == "rs"))
        .collect();
    files.sort();
    assert!(
        files.len() >= 4,
        "the scan found only {} files under {} — a walk that reaches nothing reports no \
         tokens and matches an empty record forever",
        files.len(),
        dir.display()
    );

    let mut tokens = Vec::new();
    for file in &files {
        let text = std::fs::read_to_string(file).expect("read a protocol source file");
        for line in text.lines() {
            if let Some(token) = str_const_declaration(line) {
                tokens.push(token);
            }
        }
    }
    tokens.sort();
    tokens
}

/// `NAME = "value"` if this line *declares* a public `&str` const.
fn str_const_declaration(line: &str) -> Option<String> {
    let code = line.trim_start();
    if code.starts_with("//") {
        return None;
    }
    let rest = code.strip_prefix("pub const ")?;
    let (name, rest) = rest.split_once(':')?;
    let rest = rest.trim_start().strip_prefix("&str")?;
    let rest = rest.trim_start().strip_prefix('=')?;
    let rest = rest.trim_start().strip_prefix('"')?;
    let value = rest.split_once('"')?.0;
    Some(format!("{} = {:?}", name.trim(), value))
}

