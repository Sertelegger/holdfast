/// Every protocol version whose shape is recorded under `tests/wire-shape/`.
///
/// **Append-only.** A row is the statement *"protocol M.m looked like
/// this"*, and a peer built against that version is entitled to it. The
/// current build must be the last row — you cannot be speaking a protocol
/// older than one already recorded.
const RECORDED_VERSIONS: &[(u32, u32)] = &[
    // 1.0 — 0.0.5's control protocol plus 0.0.6's attach frames. The
    // first shape recorded at all; everything before it is pre-tag and
    // has no record, which is the gap GH #18 is about.
    (1, 0),
];

/// The placeholder every opaque string field carries in this file.
///
/// [`shape`] renders text **literally**, because for an enum-valued field
/// the spelling *is* the wire contract — `"ui-bridge"` and `"UiBridge"`
/// are different protocols. That only works if free-form strings are not
/// also rendered literally, or the document would move whenever a sample
/// value did. So every `String` whose content the wire does not fix
/// carries this, and the golden shows `"<str>"` exactly where a peer is
/// free to send anything.
const STR: &str = "<str>";

// ---------------------------------------------------------------------
// Rendering the encoded form
// ---------------------------------------------------------------------

/// The CBOR a value actually encodes to, read back from the framed bytes.
///
/// Through [`frame::encode`] rather than `CborValue::serialized` on
/// purpose: these are the bytes that go on the socket, and the existing
/// key-set tests in `frames.rs` and `method.rs` read them the same way.
fn wire_form<T: Serialize>(value: &T) -> CborValue {
    let framed = frame::encode(value).expect("a wire sample must encode");
    frame::decode(&framed[LENGTH_PREFIX_BYTES..]).expect("a frame body is CBOR")
}

/// A value's shape: keys and kinds, with text kept verbatim.
///
/// Map keys are **sorted**, following §7.4's own position that the wire
/// fixes the field names and not a map order — the same reason
/// `frame_bodies_are_cbor_maps_keyed_by_the_7_4_1_field_names` compares a
/// set. Reordering a struct's fields is therefore not a wire change and
/// does not move this document.
fn shape(value: &CborValue) -> String {
    match value {
        CborValue::Null => "null".to_string(),
        CborValue::Bool(_) => "bool".to_string(),
        CborValue::Integer(_) => "int".to_string(),
        CborValue::Float(_) => "float".to_string(),
        CborValue::Bytes(_) => "bytes".to_string(),
        CborValue::Text(t) => format!("{t:?}"),
        CborValue::Array(items) => {
            let inner: Vec<String> = items.iter().map(shape).collect();
            format!("[{}]", inner.join(", "))
        }
        CborValue::Map(entries) => {
            let mut fields: Vec<String> = entries
                .iter()
                .map(|(k, v)| {
                    let key = k.as_text().expect(
                        "a wire map is keyed by text; an integer-keyed map is a different \
                         wire format and this guard would render it as one type",
                    );
                    format!("{key}: {}", shape(v))
                })
                .collect();
            fields.sort();
            format!("{{{}}}", fields.join(", "))
        }
        other => format!("UNRENDERED({other:?})"),
    }
}

/// The field names the derived [`Debug`] prints, which is every declared
/// field — including one `skip_serializing_if` kept off the wire.
///
/// Reads names only, never values: a value would put sample data in the
/// golden and make the document move whenever a fixture did.
///
/// **Sorted**, for the same reason [`shape`] sorts map keys. `Debug`
/// prints in declaration order, so an unsorted list would report a pure
/// field *reorder* as a wire change — and reordering a struct's fields
/// does not move a CBOR map, which is why §7.4's own key-set test
/// compares a set. This line answers *which fields exist*; `wire:`
/// answers what the encoder does with them.
fn declared_fields<T: Debug>(value: &T) -> Vec<String> {
    let mut names = debug_field_names(&format!("{value:?}"));
    names.sort();
    names
}

/// [`declared_fields`]'s parser, split out so it can be tested against
/// strings whose answer is known.
///
/// Depth-1 identifiers followed by `:`. Nested braces, brackets and
/// parentheses are skipped so a `Some(..)` or an inner struct does not
/// contribute its own fields, and string literals are skipped so a `:`
/// inside sample text is not read as a field boundary.
fn debug_field_names(rendered: &str) -> Vec<String> {
    let mut names = Vec::new();
    let mut depth: usize = 0;
    let mut in_string = false;
    let mut escaped = false;
    let mut ident = String::new();

    for ch in rendered.chars() {
        if in_string {
            if escaped {
                escaped = false;
            } else if ch == '\\' {
                escaped = true;
            } else if ch == '"' {
                in_string = false;
            }
            continue;
        }
        match ch {
            '"' => {
                in_string = true;
                ident.clear();
            }
            '{' | '[' | '(' => {
                depth += 1;
                ident.clear();
            }
            '}' | ']' | ')' => {
                depth = depth.saturating_sub(1);
                ident.clear();
            }
            ':' if depth == 1 && !ident.is_empty() => {
                names.push(std::mem::take(&mut ident));
            }
            c if c.is_alphanumeric() || c == '_' => ident.push(c),
            _ => ident.clear(),
        }
    }
    names
}

/// serde's own variant list for `T`, taken from the error it raises for a
/// discriminator it does not know.
///
/// This is the only enumeration in this file that cannot go stale,
/// because the `derive` generates it: a new variant is in this list the
/// moment it compiles, with no catalogue to remember to update. It is
/// also the *serialised* spelling — post-`rename`/`rename_all`, and
/// excluding `#[serde(skip)]` variants such as `ServerFrame::Unknown`,
/// which is correct since a skipped variant is not on the wire.
///
/// The extraction panics rather than returning empty if serde stops
/// phrasing the error this way. A version of this that silently answered
/// `vec![]` would record an empty variant list in the golden, match it
/// forever, and be the exact failure mode — a guard that passes because
/// it cannot see — this file is written against.
fn serde_variants<T: DeserializeOwned>(probe: CborValue) -> Vec<String> {
    let err = probe
        .deserialized::<T>()
        .err()
        .expect("the probe discriminator must not be a real variant");
    variants_in(&err.to_string())
}

/// [`serde_variants`]'s parser, split out so it can be tested against
/// messages whose answer is known.
///
/// serde phrases the list three different ways depending on how many
/// variants there are — `` expected `a` ``, `` expected `a` or `b` ``,
/// and `` expected one of `a`, `b`, `c` `` — which this guard discovered
/// the hard way on its first run, when `AttachMode` and `AttachRole`
/// (two variants each) took the middle form. So the extraction reads the
/// **backtick-delimited spans** after `expected` rather than splitting on
/// any one separator: that is the part of the phrasing all three share,
/// and it survives a fourth.
fn variants_in(message: &str) -> Vec<String> {
    assert!(
        message.contains("unknown variant"),
        "the probe discriminator did not produce serde's unknown-variant error, so this is \
         not a variant list: {message}"
    );
    let (_, tail) = message.split_once("expected ").unwrap_or_else(|| {
        panic!(
            "serde no longer reports its variant list in the form this guard reads, so the \
             guard is blind to a new frame variant. Re-derive the extraction from: {message}"
        )
    });
    let found: Vec<String> = tail
        .split('`')
        .skip(1)
        .step_by(2)
        .map(str::to_string)
        .collect();
    assert!(
        !found.is_empty(),
        "no variant names were extracted, which would record an empty catalogue and match \
         it forever. From: {message}"
    );
    found
}

/// The probe an internally-tagged frame enum rejects: a `type` no build
/// declares.
fn tagged_probe() -> CborValue {
    CborValue::Map(vec![(
        CborValue::Text("type".into()),
        CborValue::Text("HoldfastWireShapeProbeNotAVariant".into()),
    )])
}

/// The probe a string-serialised enum rejects.
fn plain_probe() -> CborValue {
    CborValue::Text("HoldfastWireShapeProbeNotAVariant".into())
}

/// The `type` tag a frame sample encodes to.
fn tag_of(value: &CborValue) -> String {
    let CborValue::Map(entries) = value else {
        panic!("§7.5's frames are CBOR maps, got {value:?}")
    };
    entries
        .iter()
        .find(|(k, _)| k.as_text() == Some("type"))
        .and_then(|(_, v)| v.as_text())
        .expect("§7.5 tags every frame with a `type`")
        .to_string()
}

