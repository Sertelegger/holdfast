//! The wire shape, recorded per protocol version (GH #18).
//!
//! Every other wire test in this tree answers *"is the shape right?"*.
//! None of them answers *"did the shape move without the version
//! moving?"*, which is the question §23.3 turns into a compatibility
//! promise and the question nothing in the tree could fail on. Six
//! pre-tag commits changed the wire and left [`PROTOCOL_MINOR`] alone;
//! that was defensible then and is not now (GH #16 ratified the `v0.0.5`
//! tag as the boundary), and the diff of the seventh looks exactly like
//! the diff of the first.
//!
//! # What this records
//!
//! A text document — [`shape_document`] — built from the **encoded
//! bytes** of the live types, and compared against
//! `tests/wire-shape/<major>.<minor>.golden`. It is keyed to the
//! serialised surface, not to the source text, which is the property
//! that decides whether a guard survives contact with real work: a
//! comment, a private helper, a renamed local, a reordered struct field
//! and a reordered `use` all leave this document byte-identical, so
//! nobody learns to bump the constant reflexively to make a red go away.
//!
//! Three dimensions per type, because no one of them sees everything:
//!
//! * **`wire:`** — the CBOR the encoder actually emits, keys sorted.
//!   Sees added, removed, renamed and retyped fields, and the `type` tag
//!   of every frame variant. Blind to a field that `skip_serializing_if`
//!   dropped, which is why the next line exists.
//! * **`declared:`** — the field names from the derived [`Debug`], which
//!   prints a field whether or not the encoder skipped it. This is what
//!   catches a new `Option` field recorded with a `None` sample: the
//!   `wire:` line would not move, and this one does.
//! * **`variants:`** — serde's own list, read out of the error it raises
//!   for an unknown discriminator (see [`serde_variants`]). Generated by
//!   the `derive`, so unlike a hand-kept catalogue it cannot be
//!   forgotten. `frames.rs`'s `KNOWN_SERVER_TYPES` is hand-kept and has
//!   the matching hole — a variant added with a `tag()` arm but no
//!   catalogue entry leaves that file's assertions green — and this line
//!   closes it for free. It is also post-`rename`, where `tag()` is a
//!   Rust method and cannot see a `#[serde(rename)]` at all.
//!
//! # How it forces the version decision
//!
//! The golden is named for the version it describes and
//! [`RECORDED_VERSIONS`] lists the ones that exist. After a wire change
//! there are exactly two green paths, and both of them move the
//! constant:
//!
//! 1. bump [`PROTOCOL_MINOR`] (additive) or [`PROTOCOL_MAJOR`]
//!    (breaking) in `protocol/handshake.rs`;
//! 2. add the new pair to [`RECORDED_VERSIONS`];
//! 3. write the new document to the golden named for it.
//!
//! The third path — editing `1.0.golden` in place — is the one this
//! guard exists to make visible. It is not prevented, because a checked-in
//! file cannot be; it is made to *read* as what it is, a claim that this
//! shape was always protocol 1.0, in a diff a reviewer sees. That is why
//! there is deliberately **no `--bless` flag and no `HOLDFAST_RECORD_…`
//! env var**: a one-command "regenerate the snapshot" affordance is
//! indistinguishable from routine hygiene, and it would train exactly the
//! reflex the issue is about. Re-recording is a copy-paste out of the
//! failure message, which is proportionate for something that happens
//! once per protocol version.
//!
//! # Scope, and the one blind spot
//!
//! Covered: the framing constants, the `control.sock` envelope and its
//! error payload, the handshake, the three `daemon/*` method payloads,
//! and the whole `attach.sock` frame catalogue.
//!
//! **Not covered, and nothing here would notice:** a *new* `daemon/*`
//! method payload struct. `Request.params` and `Response.data` are opaque
//! `CborValue`, so there is no registry of payload types to enumerate the
//! way [`serde_variants`] enumerates a frame catalogue — the list in
//! [`control_payloads`] is hand-kept and has a hand-kept list's hole. The
//! `[tokens]` section narrows it (a new method needs a `METHOD_*` const,
//! and that scan *is* exhaustive over `protocol/`), so the *method* is
//! caught even when its payload type is not. Recorded here rather than
//! papered over: a guard whose limits are written down is worth more than
//! one that implies it has none.
//!
//! Also out of scope, deliberately: `tool/<name>` params and results, and
//! the `resource/*` payloads. Those are MCP's surface, advertised to the
//! client at runtime by `tools/list` and owned by `tests/schema.rs`; they
//! are forwarded through this wire rather than defined by it.

