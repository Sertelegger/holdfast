fn shape_document() -> String {
    let mut doc = String::new();
    doc.push_str(&format!(
        "# holdfast wire shape — protocol {PROTOCOL_MAJOR}.{PROTOCOL_MINOR}\n"
    ));
    doc.push_str(
        "#\n\
         # Generated from the encoded bytes of the live types by\n\
         # crates/holdfast-core/tests/wire_shape.rs. Read that file before\n\
         # editing this one: a version already recorded here is a promise to\n\
         # every peer built against it, and rewriting a row in place is the\n\
         # thing the guard exists to make visible (GH #18).\n\
         #\n\
         #   declared: the fields the type has, including any the encoder skips\n\
         #   wire:     the CBOR actually emitted, keys sorted\n\
         #   variants: serde's own list, generated by the derive\n\
         \n",
    );

    doc.push_str("[framing]\n");
    doc.push_str(&format!("LENGTH_PREFIX_BYTES = {LENGTH_PREFIX_BYTES}\n"));
    doc.push_str(&format!("MAX_FRAME_BYTES = {MAX_FRAME_BYTES}\n"));
    doc.push('\n');

    doc.push_str("[tokens]\n");
    for token in wire_tokens() {
        doc.push_str(&format!("{token}\n"));
    }
    doc.push('\n');

    // §18.3's rows are ORDER-BOUND — §18's preamble makes the catalogue's
    // order normative, and `error_codes_are_the_spec_18_3_table_in_catalog_order`
    // is the test that owns it against the spec. This is a sequence, not a
    // set, for that reason: sorting here would record a document that a
    // reordered catalogue still matched.
    doc.push_str("[error-codes] (ordered — §18.3 row order)\n");
    for code in ErrorCode::ALL {
        doc.push_str(&format!("{}\n", code.as_str()));
    }
    doc.push('\n');

    doc.push_str("[vocabularies]\n");
    for (label, variants) in vocabularies() {
        doc.push_str(&format!("{label}: {}\n", variants.join(", ")));
    }
    doc.push('\n');

    doc.push_str("[control]\n");
    for (label, wire, declared) in control_payloads() {
        doc.push_str(&format!("{label}\n"));
        doc.push_str(&format!("  declared: {}\n", declared_line(&declared)));
        doc.push_str(&format!("  wire:     {wire}\n"));
    }
    doc.push('\n');

    doc.push_str("[attach.client]\n");
    doc.push_str(&format!(
        "variants: {}\n",
        serde_variants::<ClientFrame>(tagged_probe()).join(", ")
    ));
    for f in client_frames() {
        let wire = wire_form(&f);
        doc.push_str(&format!("ClientFrame::{}\n", tag_of(&wire)));
        doc.push_str(&format!(
            "  declared: {}\n",
            declared_line(&declared_fields(&f))
        ));
        doc.push_str(&format!("  wire:     {}\n", shape(&wire)));
    }
    doc.push('\n');

    doc.push_str("[attach.server]\n");
    doc.push_str(&format!(
        "variants: {}\n",
        serde_variants::<ServerFrame>(tagged_probe()).join(", ")
    ));
    for f in server_frames() {
        let wire = wire_form(&f);
        doc.push_str(&format!("ServerFrame::{}\n", tag_of(&wire)));
        doc.push_str(&format!(
            "  declared: {}\n",
            declared_line(&declared_fields(&f))
        ));
        doc.push_str(&format!("  wire:     {}\n", shape(&wire)));
    }

    doc
}

/// The enums that reach the wire as bare strings, with serde's list of
/// their spellings.
fn vocabularies() -> Vec<(&'static str, Vec<String>)> {
    vec![
        ("ClientKind", serde_variants::<ClientKind>(plain_probe())),
        ("AttachMode", serde_variants::<AttachMode>(plain_probe())),
        ("AttachRole", serde_variants::<AttachRole>(plain_probe())),
        ("SignalName", serde_variants::<SignalName>(plain_probe())),
        // §7.5's `ApproveBinding.decision`, a closed set of two. Listed
        // here for the same reason `SignalName` is: the `wire:` line
        // below records one *sample*, so only one of the two spellings
        // would otherwise be in the document, and `deny` is exactly the
        // value a `rename_all` change would move unnoticed.
        (
            "ApprovalDecision",
            serde_variants::<ApprovalDecision>(plain_probe()),
        ),
    ]
}

fn golden_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/wire-shape")
}

fn golden_path(major: u32, minor: u32) -> PathBuf {
    golden_dir().join(format!("{major}.{minor}.golden"))
}

/// The differing lines, as a reviewable list.
///
/// A longest-common-subsequence diff rather than a positional one. The
/// first draft compared line `i` to line `i` and, measured against a
/// single added method constant, reported **nine** changed lines: every
/// entry after the insertion point had shifted by one. A red that prints
/// nine lines when one thing moved is a red people learn to skim, and
/// this guard's whole value is that its failures get read.
fn diff(recorded: &str, current: &str) -> String {
    let a: Vec<&str> = recorded.lines().collect();
    let b: Vec<&str> = current.lines().collect();

    let mut lcs = vec![vec![0usize; b.len() + 1]; a.len() + 1];
    for i in (0..a.len()).rev() {
        for j in (0..b.len()).rev() {
            lcs[i][j] = if a[i] == b[j] {
                lcs[i + 1][j + 1] + 1
            } else {
                lcs[i + 1][j].max(lcs[i][j + 1])
            };
        }
    }

    let mut out = Vec::new();
    let (mut i, mut j) = (0, 0);
    while i < a.len() && j < b.len() {
        if a[i] == b[j] {
            i += 1;
            j += 1;
        } else if lcs[i + 1][j] >= lcs[i][j + 1] {
            out.push(format!("  -{}", a[i]));
            i += 1;
        } else {
            out.push(format!("  +{}", b[j]));
            j += 1;
        }
    }
    out.extend(a[i..].iter().map(|l| format!("  -{l}")));
    out.extend(b[j..].iter().map(|l| format!("  +{l}")));
    out.join("\n")
}

