/// `(label, wire shape, declared fields)` for one sample.
fn entry<T: Serialize + Debug>(
    label: &'static str,
    value: &T,
) -> (&'static str, String, Vec<String>) {
    (label, shape(&wire_form(value)), declared_fields(value))
}

/// The `declared:` line's body.
///
/// A unit variant such as `ClientFrame::Detach` has no fields, and the
/// record has to say so in a word rather than with an empty line — a
/// blank there is indistinguishable from a scanner that returned
/// nothing, and it would put trailing whitespace in a checked-in file.
fn declared_line(fields: &[String]) -> String {
    if fields.is_empty() {
        "(none)".to_string()
    } else {
        fields.join(", ")
    }
}

