#[test]
fn the_wire_shape_matches_the_record_for_this_protocol_version() {
    let current = shape_document();
    // A record whose diffs are noisy is a record nobody reads, and
    // trailing whitespace is the cheapest way to get there.
    assert!(
        !current.lines().any(|l| l.ends_with(' ')),
        "the generated document has trailing whitespace, which would make its diffs unreadable"
    );
    let path = golden_path(PROTOCOL_MAJOR, PROTOCOL_MINOR);

    let Ok(recorded) = std::fs::read_to_string(&path) else {
        panic!(
            "protocol {PROTOCOL_MAJOR}.{PROTOCOL_MINOR} has no recorded wire shape.\n\n\
             If the version was just bumped, this is the remaining step: write the document \
             below to {}, and add ({PROTOCOL_MAJOR}, {PROTOCOL_MINOR}) to RECORDED_VERSIONS \
             in tests/wire_shape.rs.\n\n\
             ----- begin {PROTOCOL_MAJOR}.{PROTOCOL_MINOR}.golden -----\n{current}\
             ----- end -----\n",
            path.display()
        )
    };

    // `assert!` and not `assert_eq!`: the operands here are two ~110-line
    // documents, and `assert_eq!` would print both in full as `left:` and
    // `right:` *underneath* the message — three copies of the document,
    // with the one-line diff that says what actually moved scrolled off
    // the top. Measured while proving this guard; the failure message is
    // the only part of it anyone reads.
    assert!(
        recorded == current,
        "\n\nthe daemon's wire shape is not the shape recorded for protocol \
         {PROTOCOL_MAJOR}.{PROTOCOL_MINOR}.\n\n{}\n\n\
         Something on the wire moved. Decide which kind of move it was, and record the \
         decision — both paths change PROTOCOL_MINOR or PROTOCOL_MAJOR in \
         protocol/handshake.rs:\n\n  \
         * additive (a new optional field, a new method, a server frame variant an older \
         peer may skip) -> bump PROTOCOL_MINOR;\n  \
         * breaking (a removed or renamed field, a changed type, a changed `type` tag, a \
         new *client* frame the daemon must understand) -> bump PROTOCOL_MAJOR.\n\n\
         Then add the new pair to RECORDED_VERSIONS and write the current document to \
         tests/wire-shape/<major>.<minor>.golden. The full current document is below.\n\n\
         Editing {} in place is the one fix that is not available: it claims this shape was \
         always protocol {PROTOCOL_MAJOR}.{PROTOCOL_MINOR}, and every peer built against the \
         real one disagrees. That rewrite is what this guard exists to make visible \
         (GH #18).\n\n\
         ----- begin current document -----\n{current}----- end -----\n",
        diff(&recorded, &current),
        path.display(),
    );
}

#[test]
fn the_recorded_versions_are_append_only_and_end_at_this_build() {
    assert!(
        !RECORDED_VERSIONS.is_empty(),
        "no protocol version has a recorded shape at all"
    );

    for pair in RECORDED_VERSIONS.windows(2) {
        assert!(
            pair[0] < pair[1],
            "RECORDED_VERSIONS is not in increasing order: {:?} precedes {:?}. The table is \
             a history, and a row out of order means one was rewritten rather than appended.",
            pair[0],
            pair[1]
        );
    }

    let last = *RECORDED_VERSIONS.last().expect("non-empty");
    assert_eq!(
        last,
        (PROTOCOL_MAJOR, PROTOCOL_MINOR),
        "this build speaks protocol {PROTOCOL_MAJOR}.{PROTOCOL_MINOR} but the newest recorded \
         version is {last:?}. Either the constants moved without a row being added, or a row \
         was added for a version nothing speaks yet."
    );

    // Every row has its record, and every record has its row. Without the
    // second half, renaming a golden to the new version — rather than
    // adding one — would delete an older protocol's shape and stay green.
    let on_disk: BTreeSet<String> = std::fs::read_dir(golden_dir())
        .expect("tests/wire-shape must exist")
        .map(|e| {
            e.expect("dir entry")
                .file_name()
                .to_string_lossy()
                .to_string()
        })
        .filter(|n| n.ends_with(".golden"))
        .collect();
    let expected: BTreeSet<String> = RECORDED_VERSIONS
        .iter()
        .map(|(a, b)| format!("{a}.{b}.golden"))
        .collect();
    assert_eq!(
        on_disk, expected,
        "the recorded shapes on disk are not the versions RECORDED_VERSIONS claims"
    );
}

#[test]
